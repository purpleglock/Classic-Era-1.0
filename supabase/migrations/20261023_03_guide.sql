## Благополучие системы

Оно зависит от покрытия труда: жители системы ÷ рабочие места построек. Рук в избытке — система богатеет. Застроили плотно при малом населении — рук не хватает, и доход мягко проседает. Резких обвалов нет: доход «дышит», а не рушится.

- Военные постройки ГС не дают, но рабочие места занимают.
- Соседние системы вашей державы немного делятся избытком благополучия.
- Статус системы: «в достатке», «волнения», «стагнация». Столица всегда «в достатке».

