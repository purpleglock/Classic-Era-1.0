create or replace function public.v1_x_ach(p_action text, p_target text, p_payload jsonb) returns integer
language plpgsql security definer set search_path = public as $$
declare n integer := 0;
begin
  case p_action
  when 'ach.save' then
    update v1_achievements set
      name = coalesce(p_payload->>'name', name), description = coalesce(p_payload->>'description', description),
      cond = coalesce(p_payload->>'cond', cond), reward = coalesce((p_payload->>'reward')::int, reward),
      status = coalesce(p_payload->>'status', status), updated_by = auth.uid(), updated_at = now()
     where id = p_target;
    get diagnostics n = row_count;
  when 'ach.scale' then
    -- массово: все награды = старая × k (k от 1 до 20)
    if coalesce((p_payload->>'k')::numeric, 0) not between 1 and 20 then raise exception 'bad_factor'; end if;
    update v1_achievements set reward = round(reward_old * (p_payload->>'k')::numeric / 100) * 100, updated_by = auth.uid(), updated_at = now();
    get diagnostics n = row_count;
  else raise exception 'unknown_action: %', p_action;
  end case;
  return n;
end $$;
revoke execute on function public.v1_x_ach(text, text, jsonb) from public, anon, authenticated;

