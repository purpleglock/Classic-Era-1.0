-- Классическая эра 1.0 · Достижения уходят на переработку.
-- Старые достижения жили прямо в коде (economy.js и функция ach_check): название,
-- условие и награда были зашиты намертво. Переносим их в таблицу, чтобы команда
-- проекта переименовывала их и поднимала награды в админ-панели, без программиста.
--
-- Пока статус 'rework': новые достижения не выдаются (старая ach_check новым сайтом
-- не вызывается), полученные остаются у держав. Когда команда закончит —
-- переключить статус на 'live', и выдача пойдёт по новым названиям и наградам.

create table if not exists public.v1_achievements (
  id          text primary key,               -- тот же ключ, что в faction_achievements.ach_id
  name        text not null default '',        -- новое название (пусто — ещё не придумано)
  old_name    text not null default '',        -- как называлось раньше
  description text not null default '',
  cond        text not null default '',        -- условие получения, понятным языком
  reward_old  integer not null default 0,      -- награда в старой экономике, ГС
  reward      integer not null default 0,      -- новая награда, ГС
  status      text not null default 'rework' check (status in ('rework', 'live', 'off')),
  sort        integer not null default 0,
  updated_by  uuid references auth.users(id),
  updated_at  timestamptz not null default now()
);
alter table public.v1_achievements enable row level security;
drop policy if exists v1_ach_read on public.v1_achievements;
create policy v1_ach_read on public.v1_achievements for select using (true);
revoke insert, update, delete on public.v1_achievements from anon, authenticated;
grant select on public.v1_achievements to anon, authenticated;

